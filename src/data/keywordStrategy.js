/**
 * Returns all keywords associated with a given target URL path
 * @param {string} path - URL path e.g. '/website-development'
 */
export function getKeywordsForPath(path) {
  const all = Object.values(KEYWORD_CLUSTERS).flat();
  return all.filter(k => k.targetUrl.endsWith(path) || (path === '/' && k.targetUrl === 'https://www.averqon.in/'));
}

/**
 * Returns all location-focused keywords for a specific city/state
 * @param {string} location - e.g. 'Chennai', 'Bangalore', 'Coimbatore', 'Sivakasi'
 */
export function getKeywordsByLocation(location) {
  const all = Object.values(KEYWORD_CLUSTERS).flat();
  return all.filter(k => k.location.toLowerCase() === location.toLowerCase());
}

